import { Router } from 'express';
import { protect, adminOnly } from '../middleware/auth.js';
import * as auth from '../controllers/auth.js';
import * as skills from '../controllers/skills.js';
import * as users from '../controllers/users.js';
import * as requests from '../controllers/requests.js';
import * as ratings from '../controllers/ratings.js';
import * as admin from '../controllers/admin.js';
import * as chat from '../controllers/messages.js';
import * as notes from '../controllers/notifications.js';
const r = Router();
r.get('/health', (req, res) => res.json({ success: true, status: 'ok' }));
r.post('/auth/register', auth.register);
r.post('/auth/login', auth.login);
r.post('/auth/logout', auth.logout);
r.get('/auth/me', protect, auth.me);
r.get('/skills', protect, skills.list);
r.post('/skills', protect, skills.create);
r.put('/skills/:id', protect, skills.update);
r.delete('/skills/:id', protect, skills.remove);
r.get('/users/stats', protect, users.stats);
r.put('/users/me', protect, users.updateMe);
r.get('/users/:id', protect, users.getProfile);
r.post('/requests', protect, requests.create);
r.get('/requests', protect, requests.list);
r.patch('/requests/:id/status', protect, requests.setStatus);
r.get('/requests/:id/messages', protect, chat.list);
r.post('/requests/:id/messages', protect, chat.send);
r.post('/requests/:id/rating', protect, ratings.create);
r.get('/admin/overview', protect, adminOnly, admin.overview);
r.get('/notifications', protect, notes.list);
r.patch('/notifications/read-all', protect, notes.markAllRead);
r.patch('/notifications/:id/read', protect, notes.markRead);
export default r;
